#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate supplementary figures for the detailed final report.
Run: python plot_additional_figures.py --data-dir . --output ./figures
Main risk maps and weights are generated by ship_risk_model.py.
"""
import argparse
from pathlib import Path
import numpy as np
from scipy.io import loadmat
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

NAMES=("Very low","Low","Medium","High","Very high")
CENTERS=np.array([0.,.25,.5,.75,1.])
ANCHORS={"wind":[0,4,8,12,16],
         "wave":[0,.75,1.5,3,5],
         "current":[0,.25,.5,1,1.8],
         "sst":[0,1,2,4,7],
         "tonnage":[10000,5000,2500,1000,300],
         "length":[200,140,100,60,30],
         "age":[0,5,10,20,30]}
W_H=np.array([.34301439,.46453346,.15848477,.03396737])
W_V=np.array([.29696133,.16342412,.53961455])
def score(x,knots):
    a=np.asarray(knots)
    return np.interp(x,a[::-1] if a[0]>a[-1] else a,
                     CENTERS[::-1] if a[0]>a[-1] else CENTERS)
def mu(x,knots):
    return np.maximum(0.,1.-np.abs(score(x,knots)[...,None]-CENTERS)/.25)
def save(fig,name,outdir):
    fig.tight_layout()
    fig.savefig(outdir/name,dpi=200,bbox_inches="tight")
    plt.close(fig)
def main(data_dir,outdir):
    outdir.mkdir(parents=True,exist_ok=True)
    arrays={}
    for k in ("wind","wave","current","tem"):
        arrays[k]=loadmat(data_dir/(k+".mat"))[k]
    lat=loadmat(data_dir/"wind.mat")["v_new"].ravel()
    lon=loadmat(data_dir/"wind.mat")["u_new"].ravel()
    mask=np.logical_and.reduce([np.isfinite(arrays[k]) for k in arrays])
    # Hazard and vessel membership curves.
    H=[("Wind speed (m/s)","wind",(0,20)),
       ("Significant wave height (m)","wave",(0,7)),
       ("Current speed (m/s)","current",(0,2.8)),
       ("SST stress (C)","sst",(0,8))]
    fig,axs=plt.subplots(2,2,figsize=(11,7))
    for ax,(title,key,rg) in zip(axs.flat,H):
        v=np.linspace(*rg,400)
        m=mu(v,ANCHORS[key])
        for i in range(5):ax.plot(v,m[:,i],label=NAMES[i])
        ax.set_title(title);ax.set_ylim(0,1.05);ax.grid(alpha=.2)
    axs.flat[0].legend(fontsize=8,ncol=2)
    save(fig,"hazard_membership.png",outdir)
    V=[("Tonnage (GT)","tonnage",(0,11500),2646),
       ("Length (m)","length",(20,220),95.68),
       ("Age (years)","age",(0,35),11.5)]
    fig,axs=plt.subplots(1,3,figsize=(12,4))
    for ax,(title,key,rg,value) in zip(axs,V):
        v=np.linspace(*rg,500)
        m=mu(v,ANCHORS[key])
        for i in range(5):ax.plot(v,m[:,i],label=NAMES[i])
        ax.axvline(value,linestyle="--")
        ax.set_title(title);ax.set_ylim(0,1.05);ax.grid(alpha=.2)
    axs[0].legend(fontsize=8)
    save(fig,"vessel_membership.png",outdir)
    fig,axs=plt.subplots(2,2,figsize=(11,7.5))
    for ax,(key,label) in zip(axs.flat,[
        ("wind","Wind (m/s)"),("wave","Wave (m)"),
        ("current","Current (m/s)"),("tem","Temperature (C)")]):
        vals=[arrays[key][:,:,t][mask[:,:,t]][::12] for t in range(4)]
        ax.boxplot(vals,tick_labels=["12-27","12-28","12-29","12-30"],showfliers=False)
        ax.set_title(label);ax.grid(axis="y",alpha=.2)
    save(fig,"daily_ocean_distributions.png",outdir)
    stress=np.maximum.reduce([np.zeros_like(arrays["tem"]),
                              20-arrays["tem"],arrays["tem"]-30])
    scores=np.stack([score(arrays["wind"],ANCHORS["wind"]),
                     score(arrays["wave"],ANCHORS["wave"]),
                     score(arrays["current"],ANCHORS["current"]),
                     score(stress,ANCHORS["sst"])],axis=-1)
    hs=np.einsum("ijkl,l->ijk",scores,W_H)
    vs=(W_V@np.array([score(2646,ANCHORS["tonnage"]),
                       score(95.68,ANCHORS["length"]),
                       score(11.5,ANCHORS["age"])]))
    risk=np.where(mask,np.clip(hs*(.5+vs),0,1),np.nan)
    area=np.broadcast_to(np.cos(np.deg2rad(lat))[:,None,None],mask.shape)
    fractions=[]
    for t in range(4):
        m=mask[:,:,t];s=risk[:,:,t][m];ww=area[:,:,t][m]
        fractions.append(np.histogram(s,bins=[0,.2,.4,.6,.8,1.0000001],
                                      weights=ww)[0]/ww.sum())
    frac=np.asarray(fractions)
    fig,ax=plt.subplots(figsize=(9,4.3))
    bottom=np.zeros(4)
    for i,name in enumerate(NAMES):
        ax.bar(["12-27","12-28","12-29","12-30"],100*frac[:,i],
               bottom=100*bottom,label=name)
        bottom+=frac[:,i]
    ax.legend(ncol=5,frameon=False)
    ax.set_ylabel("Risk grade area (%)")
    save(fig,"risk_zone_shares.png",outdir)
    fig,ax=plt.subplots(figsize=(9,4.3))
    for lo,hi,lab in [(0,10,"0-10N"),(10,20,"10-20N"),(20,31,"20-30N")]:
        b=[]
        for t in range(4):
            m=mask[:,:,t]&((lat>=lo)&(lat<hi))[:,None]
            b.append(np.average(risk[:,:,t][m],weights=area[:,:,t][m]))
        ax.plot(["12-27","12-28","12-29","12-30"],b,marker="o",label=lab)
    ax.legend(frameon=False);ax.set_ylabel("Area-weighted mean risk")
    save(fig,"latitudinal_trend.png",outdir)
    ii=np.argmin(abs(lat-8));jj=np.argmin(abs(lon-112));t=2
    R=mu(scores[ii,jj,t],np.array([0,.25,.50,.75,1.]))
    fig,ax=plt.subplots(figsize=(8,4))
    im=ax.imshow(R,vmin=0,vmax=1,aspect="auto")
    ax.set_yticks(range(4),["Wind","Wave","Current","SST"])
    ax.set_xticks(range(5),NAMES)
    for i in range(4):
        for k in range(5):ax.text(k,i,f"{R[i,k]:.2f}",ha="center",va="center")
    fig.colorbar(im,ax=ax,label="Membership")
    save(fig,"gridpoint_fuzzy_matrix.png",outdir)
    print("Additional figures written to:",outdir)

if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--data-dir",type=Path,default=Path("."))
    parser.add_argument("--out-dir",type=Path,default=Path("./figures"))
    args=parser.parse_args()
    main(args.data_dir,args.out_dir)
